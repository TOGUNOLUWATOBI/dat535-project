"""Before/after quality table for every completed snapshot (evidence for the report).

Profiles the newest complete Silver output of each snapshot in the checkpoint
registry and applies the publication gate, then writes a Markdown table and the
full profiles as JSON:

    bash scripts/run_quality_report.sh --data-root /srv/dat535/data \\
        --markdown docs/quality_report.md --json DATA_ROOT/metadata/quality_report.json
"""

import argparse
import json
import os
from pathlib import Path
import sys

from pipeline.quality.silver_profile import evaluate, profile_silver, read_thresholds

ROWS = [
    ("Lines: staging → Silver", lambda p: f"{p['v']['lines_staging']:,} → {p['v']['lines_silver']:,}"),
    ("Journeys: staging → accepted", lambda p: f"{p['v']['journeys_staging']:,} → {p['v']['journeys_accepted']:,}"),
    ("Journeys quarantined", lambda p: p["v"]["journeys_quarantined"]),
    ("Passing times: staging → accepted",
     lambda p: f"{p['v']['passing_times_staging']:,} → {p['v']['passing_times_accepted']:,}"),
    ("Passing times quarantined", lambda p: p["v"]["passing_times_quarantined"]),
    ("Stop definitions collapsed (identical duplicates)", lambda p: p["collapsed"]),
    ("Conflicting definitions withheld (all providers)", lambda p: p["conflicts"]),
    ("Unresolved references", lambda p: p["g"]["unresolved_references"]),
    ("Ambiguous references", lambda p: p["g"]["ambiguous_references"]),
    ("Invalid / inverted / non-monotonic times", lambda p: p["bad_times"]),
    ("Overnight passing times kept with day offset", lambda p: f"{p['t'].get('overnight_passing_times', 0):,}"),
    ("Calendar issues", lambda p: p["g"]["calendar_issues"]),
    ("Essential fields missing", lambda p: p["essential"]),
    ("Optional fields missing (stop name / route direction)",
     lambda p: f"{p['m'].get('optional_stop_name', 0):,} / {p['m'].get('optional_route_direction', 0):,}"),
    ("Service occurrences in window", lambda p: f"{p['s']['service_occurrences']:,}"),
    ("→ accepted for Gold (fixed, valid)", lambda p: f"{p['s']['eligible_fixed']:,}"),
    ("→ excluded: flexible (on demand)", lambda p: p["s"]["excluded_flexible"]),
    ("→ rejected: invalid", lambda p: p["s"]["rejected_invalid"]),
    ("Valid fixed journeys not operating in window",
     lambda p: f"{p['s']['valid_fixed_journeys_not_in_window']:,} of {p['s']['valid_fixed_journeys']:,}"),
    ("Publication gate", lambda p: p["gate"]),
]


def facts(profile, gate, provider):
    """Flatten one provider's profile into the values the table prints."""
    m = profile["missing"].get(provider, {})
    t = profile["times"].get(provider, {})
    collapsed = sum(v for k, v in profile["duplicates"].get(provider, {}).items() if k.endswith("_collapsed"))
    collapsed += sum(v for k, v in profile["duplicates"].get("NSR", {}).items() if k.endswith("_collapsed"))
    findings = [f for f in gate["findings"] if f["provider"] == provider]
    level = "fail" if any(f["level"] == "fail" for f in findings) else "warn" if findings else "pass"
    return {"v": profile["volumes"][provider], "s": profile["service"][provider], "m": m, "t": t,
            "g": gate["metrics"][provider], "collapsed": collapsed,
            "conflicts": sum(profile["duplicates"].get("_all", {}).values()),
            "bad_times": sum(t.get(k, 0) for k in ("invalid_time", "arrival_after_departure", "non_monotonic_time")),
            "essential": sum(v for k, v in m.items() if k.startswith("essential_")),
            "gate": level + (" (" + ", ".join(f["rule"] for f in findings) + ")" if findings else "")}


def markdown(results):
    out = ["# Silver quality evidence", "",
           "Generated by `pipeline/quality/report.py` from the newest complete Silver output of each",
           "snapshot. \"Before\" is the staging Parquet (every source occurrence), \"after\" is Silver.",
           "Service counts are for each snapshot's seven-day Gold window. Rules: `config/quality_thresholds.json`.",
           ""]
    for provider in sorted({p for r in results for p in r["profile"]["providers"]}):
        snaps = [r for r in results if provider in r["profile"]["providers"]]
        out += [f"## {provider}", "", "| Measure | " + " | ".join(r["snapshot_date"] for r in snaps) + " |",
                "| --- |" + " --- |" * len(snaps)]
        cells = [facts(r["profile"], r["gate"], provider) for r in snaps]
        for label, value in ROWS:
            out.append(f"| {label} | " + " | ".join(str(value(c)) for c in cells) + " |")
        out.append("")
    return "\n".join(out)


def main(argv=None):
    from pipeline.analysis.route_history import find_inputs
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--data-root", type=Path, required=True)
    parser.add_argument("--state", type=Path)
    parser.add_argument("--thresholds", type=Path, default=Path("config/quality_thresholds.json"))
    parser.add_argument("--markdown", type=Path, help="Write the table here (e.g. docs/quality_report.md)")
    parser.add_argument("--json", type=Path, help="Write all profiles and gate results here")
    parser.add_argument("--master", default="local[2]")
    args = parser.parse_args(argv)
    inputs = find_inputs(args.state or args.data_root / "pipeline_state.sqlite3")
    thresholds = read_thresholds(args.thresholds)
    from pyspark.sql import SparkSession
    if args.master.startswith("local"):
        os.environ.setdefault("PYSPARK_PYTHON", sys.executable)
    spark = (SparkSession.builder.appName("DAT535-quality-report").master(args.master)
             .config("spark.sql.shuffle.partitions", "4").config("spark.ui.showConsoleProgress", "false").getOrCreate())
    spark.sparkContext.setLogLevel("ERROR")
    try:
        results = []
        for item in inputs:
            profile = profile_silver(spark, item["silver"])
            gate = evaluate(profile, thresholds)
            results.append({"snapshot_date": item["snapshot_date"], "profile": profile, "gate": gate})
            print(f"{item['snapshot_date']}: gate {gate['status']}", flush=True)
        text = markdown(results)
        if args.markdown:
            args.markdown.write_text(text + "\n", encoding="utf-8")
        else:
            print(text)
        if args.json:
            args.json.write_text(json.dumps(results, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        return 1 if any(r["gate"]["status"] == "fail" for r in results) else 0
    finally:
        spark.stop()


if __name__ == "__main__":
    sys.exit(main())
